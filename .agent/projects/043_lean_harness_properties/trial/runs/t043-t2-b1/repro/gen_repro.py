#!/usr/bin/env python3
"""Writes one AILANG probe and one case file per counterexample, from WITNESSES below, so the
TypeScript and AILANG halves of check.sh see the same string. Run once; its outputs are kept.

  python3 -I gen_repro.py        (from this directory)
"""
import json
import os

NF = '{"error":{"code":"agent_not_found","message":"x"}}'
WITNESSES = [
    # id, property, exit, stderr
    ("B1-T2-1", "P2.1", 1, '{"error":{"code":"pane_not_found","message":"x"}}'),
    ("B1-T2-2", "P2.1", -1, NF),
    ("B1-T2-3", "P2.1", 1, '{"error":{"code":"agent_not_found","message":"nested herdr"}}'),
    ("B1-T2-4", "P2.1", 1, '{"id":"cli:agent:get","error":{"code":"agent_not_found","message":"x"}}'),
    ("B1-T2-5", "P2.1", 1, " " + NF),
    ("B1-T2-6", "P2.1", 1, NF + "\nkilled by SIGTERM"),
    ("B1-T2-7", "P2.1", 1, '{"error":{"code":"timeout"},"error":{"code":"agent_not_found"}}'),
    ("B1-T2-8", "P2.1", 1, '{"error":{"code":"agent_not_found","message":"x","n":1e400}}'),
    ("B1-T2-9", "P2.2", -1, "killed by SIGTERM"),
    ("B1-T2-10", "P2.2", 1, '{"error":{"code":"timeout","message":"nested herdr"}}'),
    ("B1-T2-11", "P2.2", 1, ""),
    ("B1-T2-12", "P2.2", 1, "error: nested herdr is disabled by default."),
    ("B1-T2-13", "P2.2", 1, "null"),
    ("B1-T2-14", "P2.2", 1, '{"error":{"code":"agent_not_found","message":"x"}'),
    # B1-T2-2 on the real runner's own shape for a signal-killed child (waiter_signal.ts).
    ("B1-T2-2r", "P2.1", -1, NF + "\nkilled by SIGTERM"),
    # Controls: inputs where the twins agree. check.sh must exit 0 on them.
    ("CTRL-1", "P2.1", 1, '{"error":{"code":"agent_not_found","message":"x"},"id":"cli:agent:get"}'),
    ("CTRL-2", "P2.2", 1, '{"error":{"code":"server_not_running","message":"x"}}'),
    ("CTRL-3", "P2.2", 2, "herdr agent commands:"),
]


def ail_lit(s):
    r = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            r.append('\\"')
        elif ch == "\\":
            r.append("\\\\")
        elif ch == "$":
            r.append("\\u{0024}")
        elif 32 <= o < 127:
            r.append(ch)
        else:
            r.append("\\u{%04x}" % o)
    return '"' + "".join(r) + '"'


AIL = """-- GENERATED by gen_repro.py: the REAL failure_code / means_agent_gone on %(id)s's witness.
-- Prints <failure_code>|<means_agent_gone>.
module %(mod)s

import std/io (println)
import std/string (concat)
import pkg/sunholo/motoko_ext_herdr/types (failure_code, means_agent_gone)

export func main() -> () ! {IO} {
  let e = %(exit)d;
  let s = %(lit)s;
  println(concat([failure_code(e, s), "|", if means_agent_gone(e, s) then "true" else "false"]))
}
"""

os.makedirs("ail", exist_ok=True)
os.makedirs("cases", exist_ok=True)
with open("ail/ailang.toml", "w") as f:
    f.write('[package]\nname = "local/t2_repro"\nversion = "0.1.0"\nedition = "1"\n\n'
            '[dependencies]\n"sunholo/motoko_ext_herdr" = { path = "../../../tree/packages/motoko-ext-herdr" }\n')
for rid, prop, ex, s in WITNESSES:
    mod = rid.lower().replace("-", "_")
    with open("ail/%s.ail" % mod, "w") as f:
        f.write(AIL % {"id": rid, "mod": mod, "exit": ex, "lit": ail_lit(s)})
    with open("cases/%s.json" % rid, "w") as f:
        json.dump({"id": rid, "property": prop, "exit": ex, "stderr": s}, f, ensure_ascii=True)
print("wrote %d witnesses" % len(WITNESSES))
