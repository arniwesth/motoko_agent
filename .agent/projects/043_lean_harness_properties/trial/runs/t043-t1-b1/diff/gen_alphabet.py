#!/usr/bin/env python3
"""Writes the shared input alphabet for the differential test into the three halves.

  python3 gen_alphabet.py <out dir>

Index 0 is UNSET (TypeScript `undefined`, Lean `none`, AILANG "" as P1.1 prescribes). The rest
are strings aimed at the gate's boundaries: around "1" in the order AILANG's `>=` uses (below,
equal, prefix-extended, above), the empty string, whitespace JS truthiness keeps, non-ASCII on
both sides of the BMP, and the characters each language escapes. Then RANDOM_N seeded random
strings over a pool with the same aim. Every triple of the alphabet is one test case, so the
three variables are crossed exhaustively over this set.
"""
import json, random, sys

FIXED = [
    None, "", "1", "0", "2", "10", "1 ", " 1", "01", "/usr/local/bin/herdr", "w1:p7", " ",
    "a", "true", "é", "１", "\t", "\n1", "-1", "~", "\"", "\\", "\U0001F600", "/",
    "!", "1\u0001", " 1", "11", "0￿",
]
POOL = ["0", "1", "2", "9", "a", "Z", " ", "/", ":", "é", "\t", "~", "!", "\U0001F600"]
RANDOM_N = 7

def alphabet():
    rng = random.Random(118)
    out = list(FIXED)
    while len(out) < len(FIXED) + RANDOM_N:
        s = "".join(rng.choice(POOL) for _ in range(rng.randint(1, 5)))
        if s not in out:
            out.append(s)
    return out

def lean_str(s):
    r = []
    for ch in s:
        o = ord(ch)
        if ch == '"': r.append('\\"')
        elif ch == '\\': r.append('\\\\')
        elif ch == '\n': r.append('\\n')
        elif ch == '\t': r.append('\\t')
        elif o < 0x20 or o == 0x7f: r.append('\\x%02x' % o)
        else: r.append(ch)
    return '"' + "".join(r) + '"'

def ail_str(s):
    r = []
    for ch in s:
        o = ord(ch)
        if ch == '"': r.append('\\"')
        elif ch == '\\': r.append('\\\\')
        elif ch == '\n': r.append('\\n')
        elif ch == '\t': r.append('\\t')
        elif ch == '$': r.append('\\u{24}')
        elif o < 0x20 or o >= 0x7f: r.append('\\u{%x}' % o)
        else: r.append(ch)
    return '"' + "".join(r) + '"'

def main():
    out = sys.argv[1]
    a = alphabet()
    with open(f"{out}/alphabet.lean", "w") as f:
        f.write("-- GENERATED by gen_alphabet.py; index 0 is unset.\n")
        f.write("def alphabetS : List (Option String) :=\n  [ ")
        f.write(",\n    ".join("none" if s is None else f"some {lean_str(s)}" for s in a))
        f.write(" ]\n")
    with open(f"{out}/alphabet.json", "w") as f:
        json.dump(a, f, ensure_ascii=True)
    with open(f"{out}/alphabet.ail", "w") as f:
        f.write("-- GENERATED by gen_alphabet.py; index 0 is unset, passed as \"\" (P1.1).\n")
        f.write("pure func alphabet() -> [string] {\n  [ ")
        f.write(",\n    ".join('""' if s is None else ail_str(s) for s in a))
        f.write(" ]\n}\n")
    print(len(a))

main()
