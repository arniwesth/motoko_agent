// gen_cases.ts — the input generator for the P1.1 differential test.
//
//   bun gen_cases.ts <out dir> [random count] [seed]
//
// Writes two files describing the SAME cases, in the same order:
//
//   cases.json      [[HERDR_ENV, HERDR_BIN_PATH, HERDR_PANE_ID], ...], null = unset.
//                   Read by gate_ts.ts, which hands each triple to the real
//                   `readHerdrEnvironment` as a NodeJS.ProcessEnv (null -> key absent).
//   gate_cases.<k>.ail  AILANG modules `gate_cases` (batches of <= 40,000 cases) exporting the
//                   same triples as literals with unset -> "" (P1.1's convention). Every
//                   character outside printable ASCII, and `$ " \`, is written as \u{hex},
//                   so the literal is the string byte-for-byte (checked: gate_ail.ail prints
//                   each string's length and gate_ts.ts the code-point count, and the
//                   comparison fails on any difference).
//
// Generators, in order (the case's generator tag is kept in cases.json's sidecar `tags`):
//   G1  exhaustive product V x V x V over a 29-value alphabet V (unset, "", "1" and its near
//       misses, whitespace, NUL, non-ASCII, `${..}`, realistic pane ids and paths).
//   G2  every string of length 0..3 over {0,1,2,space,a,NUL,é} as HERDR_ENV, crossed with
//       {unset,"","/b"," "} for HERDR_BIN_PATH and {unset,"","p"," "} for HERDR_PANE_ID.
//   G3  seeded random: each variable unset w.p. 1/5, otherwise a string of length 0..6 whose
//       characters are drawn half from a small hot alphabet and half uniformly from all
//       Unicode scalar values (surrogates excluded: an environment string cannot carry one).
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const outDir = process.argv[2];
if (!outDir) throw new Error("usage: bun gen_cases.ts <out dir> [random count] [seed]");
const randomCount = Number(process.argv[3] ?? "20000");
let seed = Number(process.argv[4] ?? "118") >>> 0;

type V = string | null;
const cases: [V, V, V][] = [];
const tags: string[] = [];

// G1
const V1: V[] = [
  null, "", "1", "0", "2", "10", "11", "1 ", " 1", "01", "true", "yes", "a", "Z", "~",
  " ", "\t", "\n", "\u0000", "1\u0000", "é", "\u{1F600}", "１", "${HERDR}", "\"", "\\",
  "w1:p7", "/usr/local/bin/herdr", "herdr",
];
for (const e of V1) for (const b of V1) for (const p of V1) { cases.push([e, b, p]); tags.push("G1"); }

// G2
const A2 = ["0", "1", "2", " ", "a", "\u0000", "é"];
const strs: string[] = [""];
let layer = [""];
for (let n = 1; n <= 3; n++) {
  const next: string[] = [];
  for (const s of layer) for (const c of A2) next.push(s + c);
  strs.push(...next);
  layer = next;
}
const B2: V[] = [null, "", "/b", " "];
const P2: V[] = [null, "", "p", " "];
for (const e of strs) for (const b of B2) for (const p of P2) { cases.push([e, b, p]); tags.push("G2"); }

// G3 — mulberry32
function rnd(): number {
  seed = (seed + 0x6d2b79f5) >>> 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const HOT = ["0", "1", "2", "9", " ", "\t", "\n", "\u0000", "a", "$", "{", "}", "\"", "\\", "/", ":", "é", "１", "\u{1F600}"];
function rchar(): string {
  if (rnd() < 0.5) return HOT[Math.floor(rnd() * HOT.length)];
  for (;;) {
    const cp = Math.floor(rnd() * 0x110000);
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    return String.fromCodePoint(cp);
  }
}
function rval(): V {
  if (rnd() < 0.2) return null;
  const n = Math.floor(rnd() * 7);
  let s = "";
  for (let i = 0; i < n; i++) s += rchar();
  // Bias toward the interesting prefix: a quarter of the HERDR_ENV-like strings start with "1".
  return s;
}
for (let i = 0; i < randomCount; i++) {
  const e = rnd() < 0.25 ? "1" + (rval() ?? "") : rval();
  const b = rnd() < 0.5 ? "/usr/local/bin/herdr" : rval();
  const p = rnd() < 0.5 ? "w1:p7" : rval();
  cases.push([e, b, p]);
  tags.push("G3");
}

function ailLit(s: V): string {
  const v = s ?? "";
  let out = "\"";
  for (const ch of v) {
    const cp = ch.codePointAt(0)!;
    if (cp >= 0x20 && cp <= 0x7e && ch !== "\"" && ch !== "\\" && ch !== "$") out += ch;
    else out += "\\u{" + cp.toString(16) + "}";
  }
  return out + "\"";
}

writeFileSync(join(outDir, "cases.json"), JSON.stringify({ cases, tags }));
// The AILANG module is written in BATCHES of at most 40,000 cases (gate_cases.<k>.ail), each a
// complete `gate_cases` module whose `base()` is the index of its first case: one module of
// 130,000 literal triples was killed for memory. run_p11.sh runs gate_ail.ail once per batch.
const CHUNK = 2000;
const BATCH = 40000;
let nb = 0;
for (let b0 = 0; b0 < cases.length; b0 += BATCH, nb++) {
  const batch = cases.slice(b0, b0 + BATCH);
  let ail = "module gate_cases\n\n-- GENERATED by gen_cases.ts; do not edit. Unset is written as \"\".\n\n";
  const names: string[] = [];
  for (let c = 0; c * CHUNK < batch.length; c++) {
    const part = batch.slice(c * CHUNK, (c + 1) * CHUNK);
    const name = `chunk_${c}`;
    names.push(name);
    ail += `pure func ${name}() -> [(string, string, string)] {\n  [\n`;
    ail += part.map(([e, b, p]) => `    (${ailLit(e)}, ${ailLit(b)}, ${ailLit(p)})`).join(",\n");
    ail += "\n  ]\n}\n\n";
  }
  ail += `export pure func base() -> int { ${b0} }\n\n`;
  ail += `export pure func chunk_count() -> int { ${names.length} }\n\n`;
  ail += `export pure func chunk(i: int) -> [(string, string, string)] {\n  match i {\n`;
  ail += names.map((n, i) => `    ${i} => ${n}(),`).join("\n");
  ail += `\n    _ => []\n  }\n}\n`;
  ail += `\nexport pure func chunk_size() -> int { ${CHUNK} }\n`;
  writeFileSync(join(outDir, `gate_cases.${nb}.ail`), ail);
}
writeFileSync(join(outDir, "batches"), String(nb));
console.error(`gen_cases: ${cases.length} cases (G1 ${tags.filter((t) => t === "G1").length}, G2 ${tags.filter((t) => t === "G2").length}, G3 ${tags.filter((t) => t === "G3").length})`);
